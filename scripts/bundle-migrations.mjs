// Runs after `drizzle-kit generate` (Node, dev/build time only). Reads the
// SQL migration files it produced and bundles them into a plain TS module the
// browser can import — the browser can't touch the filesystem, so
// drizzle-orm's own migrator (which calls Node's fs.readdirSync) can't be
// used client-side. See src/db/migrate.ts for the runtime side.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const drizzleDir = path.join(root, "..", "drizzle");
const journalPath = path.join(drizzleDir, "meta", "_journal.json");
const outPath = path.join(root, "..", "src", "db", "migrations.generated.ts");

const journal = JSON.parse(fs.readFileSync(journalPath, "utf-8"));

const migrations = journal.entries.map((entry) => {
  const sqlPath = path.join(drizzleDir, `${entry.tag}.sql`);
  const raw = fs.readFileSync(sqlPath, "utf-8");
  const statements = raw
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean);
  return { tag: entry.tag, when: entry.when, statements };
});

const banner = `// AUTO-GENERATED by scripts/bundle-migrations.mjs — do not edit by hand.
// Regenerate with: npm run db:generate
`;

const body = `export type Migration = { tag: string; when: number; statements: string[] };

export const migrations: Migration[] = ${JSON.stringify(migrations, null, 2)};
`;

fs.writeFileSync(outPath, banner + "\n" + body);
console.log(`Wrote ${migrations.length} migration(s) to ${path.relative(process.cwd(), outPath)}`);
